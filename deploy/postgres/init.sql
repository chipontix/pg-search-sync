-- Every write takes a fresh, even version from one sequence. The indexer uses it
-- as the Elasticsearch external version, so a redelivered or retried event
-- older than what is already indexed is rejected (409) instead of overwriting.
-- Deletes become tombstones at version+1 (odd): newer than the deleted row,
-- older than any later re-insert of the same id.
CREATE SEQUENCE product_version_seq START 2 INCREMENT 2;

CREATE TABLE products (
    id          bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    sku         text   NOT NULL UNIQUE,
    title       text   NOT NULL,
    brand       text   NOT NULL,
    category    text   NOT NULL,
    price_cents bigint NOT NULL,
    stock       int    NOT NULL,
    version     bigint NOT NULL,
    updated_at  timestamptz NOT NULL
);

CREATE FUNCTION products_bump_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    -- BEFORE ROW triggers run after the row lock is taken, so per row the
    -- version order equals the commit order.
    NEW.version    := nextval('product_version_seq');
    NEW.updated_at := now();
    RETURN NEW;
END $$;

CREATE TRIGGER products_version BEFORE INSERT OR UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION products_bump_version();

-- Deletes must carry the old row (version) to build the tombstone.
ALTER TABLE products REPLICA IDENTITY FULL;
